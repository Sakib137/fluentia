/// Centralized icon size tokens for Fluentia.
class AppIconSizes {
  AppIconSizes._();

  /// 12px - Badges, micro status icons
  static const double xs = 12.0;

  /// 16px - Secondary action icons, inline tags, small chevrons
  static const double sm = 16.0;

  /// 20px - Standard button icons, list item icons
  static const double md = 20.0;

  /// 24px - Navigation bar icons, app bar icons, card leading icons
  static const double lg = 24.0;

  /// 32px - Module category icons, feature banners
  static const double xl = 32.0;

  /// 40px - Large stat icons, achievement markers
  static const double xxl = 40.0;

  /// 48px - Empty state icons, hero splash illustrations
  static const double hero = 48.0;
}
