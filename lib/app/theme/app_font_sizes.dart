/// Centralized font size tokens for Fluentia.
/// Defines a clear, legible hierarchy avoiding arbitrary font sizes.
class AppFontSizes {
  AppFontSizes._();

  /// 32px - Large hero titles and key metrics
  static const double displayLarge = 32.0;

  /// 28px - Section display titles
  static const double displayMedium = 28.0;

  /// 24px - Screen headlines
  static const double displaySmall = 24.0;

  /// 22px - Prominent section titles
  static const double headlineLarge = 22.0;

  /// 20px - Standard screen headers and dialog titles
  static const double headlineMedium = 20.0;

  /// 18px - Card headlines and sub-headers
  static const double headlineSmall = 18.0;

  /// 16px - Standard component titles, primary button text
  static const double titleLarge = 16.0;

  /// 15px - Medium list titles, secondary button text
  static const double titleMedium = 15.0;

  /// 14px - Compact titles and dense row headers
  static const double titleSmall = 14.0;

  /// 15px - Primary reading body text
  static const double bodyLarge = 15.0;

  /// 14px - Standard UI body text and descriptions
  static const double bodyMedium = 14.0;

  /// 12px - Secondary body text and hints
  static const double bodySmall = 12.0;

  /// 14px - Standard action labels
  static const double labelLarge = 14.0;

  /// 12px - Medium tag labels and badge text
  static const double labelMedium = 12.0;

  /// 11px - Micro labels, CEFR tags, and badges
  static const double labelSmall = 11.0;

  /// 10px - Sub-caption and metadata timestamps
  static const double caption = 10.0;
}
