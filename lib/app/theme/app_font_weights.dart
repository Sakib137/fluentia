import 'package:flutter/material.dart';

/// Centralized font weight tokens for Fluentia.
class AppFontWeights {
  AppFontWeights._();

  /// Regular text (body copy, input text, hints)
  static const FontWeight regular = FontWeight.w400;

  /// Medium text (subtitles, secondary labels, emphasis)
  static const FontWeight medium = FontWeight.w500;

  /// Semi-bold text (titles, buttons, badges, section headers)
  static const FontWeight semiBold = FontWeight.w600;

  /// Bold text (headlines, metrics, strong emphasis)
  static const FontWeight bold = FontWeight.w700;
}
